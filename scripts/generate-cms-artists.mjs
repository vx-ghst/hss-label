import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const defaultContentDirectory = resolve(projectRoot, 'content/artists');
const defaultOutputFile = resolve(projectRoot, 'src/app/core/generated/cms-artists.generated.ts');
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const duplicateFields = ['id', 'slug', 'status', 'name', 'image', 'featured', 'sortOrder', 'links'];

export async function loadCmsArtists(contentDirectory = defaultContentDirectory) {
  const files = await listJsonFiles(contentDirectory);
  if (files.length === 0) return { cmsFilesExist: false, publishedArtists: [] };

  const entries = [];
  const slugs = new Map();
  const ids = new Map();

  for (const file of files) {
    const entry = await readArtistFile(file);
    ensureUnique(entry.slug, file, slugs, 'slug');
    ensureUnique(entry.id, file, ids, 'identifiant');
    entries.push(entry);
  }

  return {
    cmsFilesExist: true,
    publishedArtists: entries.filter((artist) => artist.status === 'published'),
  };
}

export async function generateCmsArtists({
  contentDirectory = defaultContentDirectory,
  outputFile = defaultOutputFile,
} = {}) {
  const result = await loadCmsArtists(contentDirectory);
  const source = `// Generated by scripts/generate-cms-artists.mjs. Do not edit manually.
import type { Artist } from '../artist.model';

export const cmsArtistFilesExist = ${result.cmsFilesExist};
export const cmsPublishedArtists: readonly Artist[] = ${JSON.stringify(result.publishedArtists, null, 2)};
`;

  await mkdir(dirname(outputFile), { recursive: true });
  await writeFile(outputFile, source, 'utf8');
  return result;
}

async function listJsonFiles(contentDirectory) {
  let entries;
  try {
    entries = await readdir(contentDirectory, { withFileTypes: true });
  } catch (error) {
    if (error?.code === 'ENOENT') return [];
    throw error;
  }

  return entries
    .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith('.json'))
    .map((entry) => resolve(contentDirectory, entry.name))
    .sort();
}

async function readArtistFile(file) {
  let raw;
  try {
    raw = JSON.parse(await readFile(file, 'utf8'));
  } catch (error) {
    throw buildError(file, `JSON invalide (${error.message})`);
  }

  const root = expectObject(raw, file, 'la racine');
  const french = validateLocale(root.fr, file, 'fr');
  const english = root.en === undefined ? undefined : validateLocale(root.en, file, 'en');

  if (english) {
    for (const field of duplicateFields) {
      if (JSON.stringify(english[field]) !== JSON.stringify(french[field])) {
        throw buildError(file, `le champ dupliqué "${field}" diffère entre fr et en`);
      }
    }
  }

  return {
    id: french.id,
    slug: french.slug,
    status: french.status,
    name: french.name,
    shortBio: french.shortBio,
    biography: french.biography,
    image: french.image,
    links: french.links,
    featured: french.featured,
    sortOrder: french.sortOrder,
    translations: {
      fr: { shortBio: french.shortBio, biography: french.biography },
      ...(english ? { en: { shortBio: english.shortBio, biography: english.biography } } : {}),
    },
  };
}

function validateLocale(value, file, locale) {
  const entry = expectObject(value, file, `la locale ${locale}`);
  const status = expectString(entry.status, file, `${locale}.status`);
  if (status !== 'draft' && status !== 'published') {
    throw buildError(file, `${locale}.status doit valoir "draft" ou "published"`);
  }

  const slug = expectString(entry.slug, file, `${locale}.slug`);
  if (!slugPattern.test(slug)) {
    throw buildError(file, `${locale}.slug doit être un slug en minuscules sans espace`);
  }

  const featured = entry.featured;
  if (typeof featured !== 'boolean') {
    throw buildError(file, `${locale}.featured doit être un booléen`);
  }

  const sortOrder = entry.sortOrder;
  if (!Number.isInteger(sortOrder)) {
    throw buildError(file, `${locale}.sortOrder doit être un nombre entier`);
  }

  return {
    id: expectString(entry.id, file, `${locale}.id`),
    slug,
    status,
    name: expectString(entry.name, file, `${locale}.name`),
    shortBio: expectString(entry.shortBio, file, `${locale}.shortBio`),
    biography: expectString(entry.biography, file, `${locale}.biography`),
    image: expectString(entry.image, file, `${locale}.image`),
    links: validateLinks(entry.links, file, locale),
    featured,
    sortOrder,
  };
}

function validateLinks(value, file, locale) {
  if (value === undefined) return [];
  if (!Array.isArray(value)) throw buildError(file, `${locale}.links doit être une liste`);

  return value.map((link, index) => {
    const item = expectObject(link, file, `${locale}.links[${index}]`);
    return {
      label: expectString(item.label, file, `${locale}.links[${index}].label`),
      url: expectString(item.url, file, `${locale}.links[${index}].url`),
    };
  });
}

function expectObject(value, file, field) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw buildError(file, `${field} doit être un objet`);
  }
  return value;
}

function expectString(value, file, field) {
  if (typeof value !== 'string' || value.trim() === '') {
    throw buildError(file, `${field} est requis et doit être une chaîne non vide`);
  }
  return value.trim();
}

function ensureUnique(value, file, values, label) {
  const previous = values.get(value);
  if (previous) {
    throw buildError(
      file,
      `${label} dupliqué "${value}" (déjà défini dans ${relative(projectRoot, previous)})`,
    );
  }
  values.set(value, file);
}

function buildError(file, message) {
  return new Error(`[CMS Artists] ${relative(projectRoot, file)} : ${message}`);
}

const invokedFile = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : '';
if (import.meta.url === invokedFile) {
  generateCmsArtists()
    .then(({ cmsFilesExist, publishedArtists }) => {
      const message = cmsFilesExist
        ? `${publishedArtists.length} artiste(s) CMS publié(s)`
        : 'aucun fichier CMS; fallback Angular conservé';
      console.log(`[CMS Artists] ${message}.`);
    })
    .catch((error) => {
      console.error(error.message);
      process.exitCode = 1;
    });
}
